let LANG = localStorage.getItem('basokita_lang') || 'id';
function applyLang(l){
  LANG = l; localStorage.setItem('basokita_lang', l);
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const k = el.getAttribute('data-i18n');
    if(I18N[l][k] !== undefined) el.innerHTML = I18N[l][k].replace(/\n/g,'<br>');
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const k = el.getAttribute('data-i18n-ph');
    if(I18N[l][k] !== undefined) el.placeholder = I18N[l][k];
  });
  document.querySelectorAll('.lang button').forEach(b=>{
    b.classList.toggle('active', b.dataset.lang===l);
  });
  document.documentElement.lang = l==='id'?'id':'en';
}
document.addEventListener('DOMContentLoaded', ()=>{
  applyLang(LANG);
  document.querySelectorAll('.lang button').forEach(b=>{
    b.addEventListener('click', ()=>applyLang(b.dataset.lang));
  });
  const ham = document.querySelector('.hamburger');
  const links = document.querySelector('.nav-links');
  if(ham && links) ham.addEventListener('click', ()=>links.classList.toggle('open'));
  // reveal
  const io = new IntersectionObserver(es=>es.forEach(e=>{
    if(e.isIntersecting){e.target.classList.add('visible');io.unobserve(e.target);}
  }),{threshold:.12});
  document.querySelectorAll('.reveal').forEach(el=>io.observe(el));
  // filter
  const fbtns = document.querySelectorAll('.filters button');
  const cards = document.querySelectorAll('.menu-grid .card');
  fbtns.forEach(btn=>btn.addEventListener('click', ()=>{
    fbtns.forEach(b=>b.classList.remove('active')); btn.classList.add('active');
    const f = btn.dataset.filter;
    cards.forEach(c=>{
      const cats = (c.dataset.cat||'').split(' ');
      const show = f==='all' || cats.includes(f);
      c.style.display = show?'':'none';
      if(show){c.classList.remove('visible');requestAnimationFrame(()=>c.classList.add('visible'));}
    });
  }));
  // contact form
  const form = document.getElementById('contactForm');
  if(form) form.addEventListener('submit', e=>{
    e.preventDefault();
    const toast = document.getElementById('toast');
    if(toast){toast.textContent = I18N[LANG].toast_ok; toast.classList.add('show');
      setTimeout(()=>toast.classList.remove('show'),3000);}
    form.reset();
  });
});
const WA_NUMBER = "6281234567890";
function orderWA(product){
  const msg = LANG==='id'
    ? `Halo BasoKita! Saya mau pesan ${product}. Terima kasih!`
    : `Hello BasoKita! I'd like to order ${product}. Thank you!`;
  window.open(`https://wa.me/${WA_NUMBER}?text=${encodeURIComponent(msg)}`,'_blank');
}
